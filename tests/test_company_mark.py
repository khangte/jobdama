"""회사 마크 글자 규칙(docs/design/2026-11-10-company-mark-options.md)."""

import pytest

from app.parsers.common import company_mark


@pytest.mark.parametrize("name,mark", [
    ("(주)잡담아", "잡"), ("㈜잡담아", "잡"), ("주식회사 잡담아", "잡"), ("잡담아(주)", "잡"), ("잡담아 주식회사", "잡"),
    ("주식회사잡담아", "잡"), ("잡담아주식회사", "잡"), ("　（ 주 ） 잡담아　", "잡"), ("(주) 주식회사 잡담아 (유)", "잡"),
    ("(유)네오", "네"), ("유한책임회사 네오", "네"), ("(재)미래", "미"), ("사단법인 미래", "미"), ("(합)미래", "미"),
    ("우주개발", "우"), ("주연테크", "주"), ("유니온", "유"), ("우리주식회사연구소", "우"),
    ("(AI)랩", "A"), ("[브랜드] 연구소", "브"), ("acme", "A"), ("ＡＣＭＥ", "A"), ("AT&T", "A"), ("3M", "3"),
    ("Élan", "É"), ("東京研究所", "東"), ("ßeta", "ß"), ("e\u0301cole", "é"), ("क्षेत्र", "क्षे"), ("\u0915\u094d\u200d\u0937", "\u0915\u094d\u200d\u0937"), ("a\u200cb", "A\u200c"), ("a\u200d\u00dfeta", "A\u200d"), ("क् company", "क्"), ("🚀 잡담아", "잡"), ("LLC Example", "L"),
    ("(주)", "↗"), ("주식회사", "↗"), ("()", "↗"), ("🚀", "↗"), ("  ", "↗"), ("", "↗"), (None, "↗"),
])
def test_company_mark(name, mark):
    """설계 문서 예외 표의 기대값."""
    assert company_mark(name) == mark
